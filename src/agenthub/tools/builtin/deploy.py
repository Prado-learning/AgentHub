from __future__ import annotations

from html import escape
from pathlib import Path
from agenthub.infrastructure.config.paths import data_root
from uuid import uuid4

from agenthub.sandbox import current_sandbox
from agenthub.tools.schemas import ToolResult


DEPLOYMENT_DIR = data_root() / "deployments"


def deploy_tool(
    title: str = "AgentHub Static Deployment",
    code: str = "",
    preview_html: str = "",
    **_: object,
) -> ToolResult:
    deployment_id = f"dep_{uuid4().hex[:12]}"
    target_dir = DEPLOYMENT_DIR / deployment_id
    html = preview_html or _html_from_code(title, code)
    _write_deployment(target_dir / "index.html", html)
    preview_url = f"/deployments/{deployment_id}/index.html"
    logs = (
        f"Deployment {deployment_id} completed.\n"
        f"Generated static preview at {preview_url}."
    )
    return ToolResult(
        id="deployment_result",
        type="deployment",
        title=title,
        content=logs,
        preview_url=preview_url,
        metadata={
            "deployment_id": deployment_id,
            "status": "success",
            "logs": logs,
            "deployment_url": preview_url,
        },
    )


def _write_deployment(target: Path, html: str) -> None:
    """Write through the run's sandbox when one is bound.

    Deploy is an L3 tool: it only ever runs as an approved step, and the
    write is recorded in the sandbox audit trail alongside everything
    else that step did.
    """
    sandbox = current_sandbox()
    if sandbox is not None:
        sandbox.write_path(target, html)
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html, encoding="utf-8")


def _html_from_code(title: str, code: str) -> str:
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>{escape(title)}</title>
    <style>
      body {{ font-family: Inter, system-ui, sans-serif; margin: 0; padding: 32px; background: #f8fafc; color: #0f172a; }}
      main {{ max-width: 860px; margin: 0 auto; background: #fff; border: 1px solid #e2e8f0; border-radius: 18px; padding: 24px; }}
      pre {{ white-space: pre-wrap; background: #0f172a; color: #e2e8f0; border-radius: 14px; padding: 16px; overflow: auto; }}
    </style>
  </head>
  <body>
    <main>
      <h1>{escape(title)}</h1>
      <p>This static deployment was generated by AgentHub.</p>
      <pre>{escape(code or "No source artifact was available.")}</pre>
    </main>
  </body>
</html>"""
